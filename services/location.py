FULL_NAME_TO_BASE = {p: p.rstrip("都道府県") for p in PREFECTURE_OPTIONS}
FULL_NAME_TO_BASE.update({"東京都": "東京", "京都府": "京都", "大阪府": "大阪", "北海道": "北海道"})

ALIASES = {"tokyo": "東京", "osaka": "大阪", "kyoto": "京都", "hokkaido": "北海道", "kanagawa": "神奈川"}

def normalize_prefecture_name(value: str | None) -> str:
    if not value:
        return ""
    v = value.strip()
    if v in FULL_NAME_TO_BASE:
        return FULL_NAME_TO_BASE[v]
    if v.lower() in ALIASES:
        return ALIASES[v.lower()]
    if v.endswith(("都", "府", "県")):
        v = v[:-1]
    return v

def resolve_prefecture(prefecture: str | None) -> tuple[str, float, float]:
    name = normalize_prefecture_name(prefecture)
    coords = PREFECTURE_COORDS.get(name)
    if not coords:
        raise ValueError(f"都道府県の座標が未登録です: {prefecture}")
    return name, coords[0], coords[1]
